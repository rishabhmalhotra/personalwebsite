#!/usr/bin/env node
/**
 * Syncs the Spotify playlist into js/data/playlist.js.
 * Reads the public playlist URI and writes track data for the audio panel.
 * This is a stub - implement with the Spotify Web API as needed.
 */
import { writeFile } from 'fs/promises';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const root = join(__dirname, '..');

const PLAYLIST_URI = 'spotify:playlist:6YGvluoYkCURQePkFMoYqW';

async function main() {
  const playlistPath = join(root, 'js', 'data', 'playlist.js');
  const content = `// Generated by npm run sync:playlist. Do not edit by hand.\nexport const playlistUri = '${PLAYLIST_URI}';\nexport const tracks = [];\n`;
  await writeFile(playlistPath, content);
  console.log(`Synced playlist to ${playlistPath}`);
}

main();
